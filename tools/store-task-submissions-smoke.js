'use strict';
const assert=require('assert/strict'),service=require('../lib/store-tasks');
(async()=>{
  const {db}=await require('./store-tasks-fixture')();
  const admin={id:1,username:'admin',position_permissions:['*']},staff={id:2,username:'staff',position_permissions:['store-tasks.execute']};
  const template=service.saveTemplate(db,{title:'收档验收',questions:[{id:'check',title:'检查情况',type:'text',required:true}]},admin).id;
  service.dispatch(db,{template_id:template,store_ids:[1,2],frequency:'once',from:'2026-10-07',to:'2026-10-07',due_time:'10:00'},admin);
  const task=service.list(db,{from:'2026-10-07',to:'2026-10-07',store_id:1},1)[0];
  service.writeAnswer(db,task.id,{question_id:'check',revision:0,value:'旧版答案'},staff,1);
  service.submit(db,task.id,{revision:1},staff,1);
  let list=service.submissionList(db,{},null);
  assert.equal(list.total,1);assert.equal(list.rows[0].title,'收档验收');assert.equal(list.counts.pending,1);
  const oldId=list.rows[0].id;
  assert.throws(()=>service.submissionDetail(db,oldId,2),/无权/);
  assert.equal(service.submissionList(db,{},2).total,0);
  assert.throws(()=>service.submissionList(db,{store_id:2},1),/无权/);
  assert.throws(()=>service.submissionList(db,{page:-1}),/分页/);
  assert.throws(()=>service.submissionList(db,{from:'2026-02-30',to:'2026-03-01'}),/日期/);
  assert.throws(()=>service.review(db,task.id,{version:1,status:'rejected',note:'  '},admin,1),/意见/);
  assert.throws(()=>service.review(db,task.id,{version:1,note:'无状态'},admin,1),/状态/);
  assert.throws(()=>service.review(db,task.id,{version:1,status:'approved'},staff,1),/权限/);
  service.review(db,task.id,{version:1,status:'rejected',note:'请补充检查记录'},admin,1);
  assert.equal(service.submissionDetail(db,oldId,1).review_note,'请补充检查记录');
  service.writeAnswer(db,task.id,{question_id:'check',revision:3,value:'修改后的答案'},staff,1);
  service.submit(db,task.id,{revision:4},staff,1);
  assert.equal(service.submissionDetail(db,oldId,1).current,false);
  assert.equal(service.submissionDetail(db,oldId,1).snapshot[0].contributions[0].response.value,'旧版答案');
  assert.throws(()=>service.review(db,task.id,{version:1,status:'approved'},admin,1),/版本/);
  const current=service.detail(db,task.id,1).submissions[0];
  service.review(db,task.id,{version:2,status:'approved',note:''},admin,1);
  const receipt=service.detail(db,task.id,1).submissions[0];
  assert.equal(receipt.status,'approved');assert.equal(receipt.review_note,'');assert(receipt.reviewed_at);assert.equal(receipt.reviewed_name,'admin');
  db.run('UPDATE store_task_submissions SET submitted_at=? WHERE id=?',['2026-10-07T16:01:00.000Z',oldId]);
  db.run('UPDATE store_task_submissions SET submitted_at=? WHERE id=?',['2026-10-08T16:00:00.000Z',current.id]);
  assert.equal(service.submissionList(db,{from:'2026-10-08',to:'2026-10-08'},1).total,1);
  list=service.submissionList(db,{page:2,page_size:1},1);assert.equal(list.total,2);assert.equal(list.rows[0].id,oldId);
  assert.equal(service.submissionList(db,{status:'approved'},1).rows[0].id,current.id);
  assert.equal(service.submissionList(db,{},1).counts.rejected,1);
  console.log('PASS: all submission versions, snapshots, pagination, Beijing submission dates, scope/permission denial, status required, rejection notes, optional approval notes, stale version rejection and mobile receipt fields');
})().catch(e=>{console.error(e);process.exitCode=1});
